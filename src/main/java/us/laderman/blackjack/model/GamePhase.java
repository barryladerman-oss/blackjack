package us.laderman.blackjack.model;

/**
 * Enum representing the phases of a Blackjack game.
 */
public enum GamePhase {
    /**
     * Player's turn phase.
     */
    PLAYER_TURN,
    /**
     * Dealer's turn phase.
     */
    DEALER_TURN,
    /**
     * Game complete phase.
     */
    COMPLETE
}
